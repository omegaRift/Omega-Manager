// Builds the Omega Manager Android app (android/dist/omega-manager.apk) with only the Android SDK's own tools:
// aapt2 (resources) -> javac -> d8 (dex) -> zipalign -> apksigner. No Gradle.
//   node android/build.mjs          (or: npm run android)
// Needs: a JDK (javac, keytool) and the Android SDK with build-tools 35.0.1 and platforms;android-35
// (ANDROID_HOME, or %LOCALAPPDATA%\Android\Sdk).
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync, copyFileSync } from 'node:fs';
import { createHash, randomBytes } from 'node:crypto';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateRawSync, crc32 } from 'node:zlib';
import { decodePng } from '../lib/png.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, '..');
const SDK = process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT || join(process.env.LOCALAPPDATA || '', 'Android', 'Sdk');
const BT = join(SDK, 'build-tools', '35.0.1');
const ANDROID_JAR = join(SDK, 'platforms', 'android-35', 'android.jar');
const OUT = join(HERE, 'build');
const DIST = join(HERE, 'dist');
const KEYSTORE = join(HERE, 'keystore', 'omega-sideload.jks');
// The signing key and its password live in keystore/ (git-ignored). Keep that folder: an app signed with a
// different key can't update the installed one (phones would have to uninstall it first).
const KEY_PASS_FILE = join(HERE, 'keystore', 'password.txt');
const PHONE_PORT = 8444;                     // Tailscale serve port (main.js PHONE_SERVE_PORT)
const exe = name => join(BT, process.platform === 'win32' && !/\./.test(name) ? `${name}.exe` : name);
const isWin = process.platform === 'win32';

function javaBin(name) {
  const home = process.env.JAVA_HOME;
  const p = home ? join(home, 'bin', isWin ? `${name}.exe` : name) : name;
  return home && existsSync(p) ? p : name;
}
function run(cmd, args, opts = {}) {
  const bat = /\.bat$/i.test(cmd);
  try {
    return execFileSync(bat ? (process.env.ComSpec || 'cmd.exe') : cmd, bat ? ['/d', '/s', '/c', `"${[cmd, ...args].map(a => /[\s&()]/.test(a) ? `"${a}"` : a).join(' ')}"`] : args,
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true, windowsVerbatimArguments: bat, ...opts });
  } catch (e) {
    throw new Error(`${cmd.split(/[\\/]/).pop()} failed:\n${(e.stdout || '') + (e.stderr || '') || e.message}`);
  }
}
const step = (n, label) => console.log(`[${n}/7] ${label}`);

// ---------- icons from the user's Omega.png ----------
// Each opaque pixel becomes a 1x1 square; squares of one colour share a path (runs merged per row).
function pixelPaths(img, { ox = 0, oy = 0, scale = 1, silhouette = null } = {}) {
  const byColor = new Map();
  for (let y = 0; y < img.height; y++) {
    let x = 0;
    while (x < img.width) {
      const i = (y * img.width + x) * 4;
      if (img.rgba[i + 3] < 128) { x++; continue; }
      const key = silhouette || '#' + [0, 1, 2].map(k => img.rgba[i + k].toString(16).padStart(2, '0')).join('').toUpperCase();
      let w = 1;
      while (x + w < img.width) {
        const j = (y * img.width + x + w) * 4;
        if (img.rgba[j + 3] < 128) break;
        const k2 = silhouette || '#' + [0, 1, 2].map(k => img.rgba[j + k].toString(16).padStart(2, '0')).join('').toUpperCase();
        if (k2 !== key) break;
        w++;
      }
      const f = n => +(n).toFixed(3);
      const d = `M${f(ox + x * scale)},${f(oy + y * scale)}h${f(w * scale)}v${f(scale)}h${f(-w * scale)}z`;
      byColor.set(key, (byColor.get(key) || '') + d);
      x += w;
    }
  }
  return [...byColor].map(([color, d]) => `    <path android:fillColor="${color}" android:pathData="${d}" />`).join('\n');
}
const vector = (size, viewport, paths) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by build.mjs from Omega.png. Edit the PNG, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${size}dp" android:height="${size}dp"
    android:viewportWidth="${viewport}" android:viewportHeight="${viewport}">
${paths}
</vector>
`;

function generateIcons(gen) {
  const img = decodePng(readFileSync(join(APP, 'Omega.png')));
  const n = Math.max(img.width, img.height);
  mkdirSync(join(gen, 'drawable'), { recursive: true });
  mkdirSync(join(gen, 'mipmap-anydpi-v26'), { recursive: true });
  // In-app logo: the picture as it is.
  writeFileSync(join(gen, 'drawable', 'ic_omega.xml'), vector(48, n, pixelPaths(img)));
  // Status-bar icon: Android draws it as a white silhouette; 2 px of padding on each side.
  writeFileSync(join(gen, 'drawable', 'ic_stat.xml'), vector(24, n + 4, pixelPaths(img, { ox: 2, oy: 2, silhouette: '#FFFFFFFF' })));
  // Launcher: an adaptive icon. The picture fills the 66 dp safe zone of the 108 dp canvas.
  const scale = 60 / n, off = (108 - 60) / 2;
  writeFileSync(join(gen, 'drawable', 'ic_launcher_fg.xml'), vector(108, 108, pixelPaths(img, { ox: off, oy: off, scale })));
  writeFileSync(join(gen, 'mipmap-anydpi-v26', 'ic_launcher.xml'), `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/launcher_bg" />
    <foreground android:drawable="@drawable/ic_launcher_fg" />
    <monochrome android:drawable="@drawable/ic_launcher_fg" />
</adaptive-icon>
`);
}

// ---------- adding classes.dex to the APK aapt2 made (store the other entries untouched) ----------
function addToZip(zipPath, name, data) {
  const zip = readFileSync(zipPath);
  let eocd = zip.length - 22;
  while (eocd >= 0 && zip.readUInt32LE(eocd) !== 0x06054b50) eocd--;
  if (eocd < 0) throw new Error('Not a zip file: ' + zipPath);
  const count = zip.readUInt16LE(eocd + 10), cdSize = zip.readUInt32LE(eocd + 12), cdOff = zip.readUInt32LE(eocd + 16);
  const nameBuf = Buffer.from(name, 'utf8');
  const comp = deflateRawSync(data, { level: 9 });
  const crc = crc32(data);
  const local = Buffer.alloc(30);
  local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0, 6); local.writeUInt16LE(8, 8);
  local.writeUInt16LE(0, 10); local.writeUInt16LE(0x21, 12);   // 1980-01-01, like aapt2's entries local.writeUInt32LE(crc, 14); local.writeUInt32LE(comp.length, 18); local.writeUInt32LE(data.length, 22);
  local.writeUInt16LE(nameBuf.length, 26); local.writeUInt16LE(0, 28);
  const central = Buffer.alloc(46);
  central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6); central.writeUInt16LE(0, 8); central.writeUInt16LE(8, 10);
  central.writeUInt16LE(0, 12); central.writeUInt16LE(0x21, 14); central.writeUInt32LE(crc, 16); central.writeUInt32LE(comp.length, 20); central.writeUInt32LE(data.length, 24);
  central.writeUInt16LE(nameBuf.length, 28); central.writeUInt32LE(cdOff, 42);
  const body = Buffer.concat([zip.subarray(0, cdOff), local, nameBuf, comp]);
  const cd = Buffer.concat([zip.subarray(cdOff, cdOff + cdSize), central, nameBuf]);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(count + 1, 8); end.writeUInt16LE(count + 1, 10);
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(body.length, 16);
  writeFileSync(zipPath, Buffer.concat([body, cd, end]));
}

const listFiles = (dir, ext) => readdirSync(dir, { withFileTypes: true }).flatMap(e => e.isDirectory() ? listFiles(join(dir, e.name), ext) : e.name.endsWith(ext) ? [join(dir, e.name)] : []);

export function build({ quiet = false } = {}) {
  if (quiet) console.log = () => {};
  for (const [what, p] of [['Android build-tools 35.0.1', BT], ['Android 15 platform (android-35)', ANDROID_JAR]]) {
    if (!existsSync(p)) throw new Error(`${what} not found at ${p}. Install it with the Android SDK's sdkmanager.`);
  }
  const pkg = JSON.parse(readFileSync(join(APP, 'package.json'), 'utf8'));
  const versionName = pkg.version;
  const versionCode = Math.floor(Date.now() / 60000) - 29_000_000;   // grows every minute, so a new build always installs over the old one

  rmSync(OUT, { recursive: true, force: true });
  const gen = join(OUT, 'gen-res'), cls = join(OUT, 'classes'), src = join(OUT, 'gen-src'), dex = join(OUT, 'dex');
  for (const d of [OUT, gen, cls, src, dex, DIST]) mkdirSync(d, { recursive: true });

  step(1, 'icons from Omega.png, and this PC\'s address');
  generateIcons(gen);
  const pcUrl = pcAddress();
  mkdirSync(join(src, 'lab', 'omega', 'manager'), { recursive: true });
  writeFileSync(join(src, 'lab', 'omega', 'manager', 'Defaults.java'),
    `package lab.omega.manager;\n\n/** Generated by build.mjs. */\nfinal class Defaults {\n    /** The address the pairing screen starts with: this PC on Tailscale. */\n    static final String URL = ${JSON.stringify(pcUrl)};\n}\n`);
  console.log(pcUrl ? `      the app will start with ${pcUrl}` : '      no Tailscale address found: the app will ask for the PC address (set OMEGA_PC_URL to choose one)');

  step(2, 'resources (aapt2)');
  run(exe('aapt2'), ['compile', '--dir', join(HERE, 'res'), '-o', join(OUT, 'res.zip')]);
  run(exe('aapt2'), ['compile', '--dir', gen, '-o', join(OUT, 'gen.zip')]);
  const base = join(OUT, 'base.apk');
  run(exe('aapt2'), ['link', '-o', base, '-I', ANDROID_JAR, '--manifest', join(HERE, 'AndroidManifest.xml'),
    '--java', src, '--min-sdk-version', '26', '--target-sdk-version', '35',
    '--version-code', String(versionCode), '--version-name', versionName,
    '-R', join(OUT, 'res.zip'), '-R', join(OUT, 'gen.zip'), '--auto-add-overlay']);

  step(3, 'Java (javac)');
  const sources = [...listFiles(join(HERE, 'src'), '.java'), ...listFiles(src, '.java')];
  writeFileSync(join(OUT, 'sources.txt'), sources.map(s => `"${s.replace(/\\/g, '/')}"`).join('\n'));
  // java.* comes from the JDK's Java 8 API (android.jar's LambdaMetafactory stub has no metafactory, so lambdas
  // would not compile against it as the boot class path); android.* and org.json come from android.jar. d8 desugars.
  run(javaBin('javac'), ['--release', '8', '-classpath', ANDROID_JAR, '-encoding', 'UTF-8', '-Xlint:-options', '-d', cls, `@${join(OUT, 'sources.txt')}`]);
  run(javaBin('jar'), ['cf', join(OUT, 'classes.jar'), '-C', cls, '.']);

  step(4, 'dex (d8)');
  run(join(BT, isWin ? 'd8.bat' : 'd8'), ['--release', '--min-api', '26', '--lib', ANDROID_JAR, '--output', dex, join(OUT, 'classes.jar')]);
  const unsigned = join(OUT, 'unsigned.apk');
  copyFileSync(base, unsigned);
  addToZip(unsigned, 'classes.dex', readFileSync(join(dex, 'classes.dex')));

  step(5, 'align (zipalign)');
  const aligned = join(OUT, 'aligned.apk');
  run(exe('zipalign'), ['-f', '-p', '4', unsigned, aligned]);

  step(6, 'sign (apksigner)');
  if (!existsSync(KEYSTORE)) {
    mkdirSync(dirname(KEYSTORE), { recursive: true });
    writeFileSync(KEY_PASS_FILE, randomBytes(24).toString('base64url'));
    const pass = readFileSync(KEY_PASS_FILE, 'utf8').trim();
    run(javaBin('keytool'), ['-genkeypair', '-keystore', KEYSTORE, '-alias', 'omega', '-keyalg', 'RSA', '-keysize', '2048', '-validity', '10000',
      '-storepass', pass, '-keypass', pass, '-dname', 'CN=Omega Manager']);
  }
  if (!existsSync(KEY_PASS_FILE)) throw new Error(`The signing key's password file is missing: ${KEY_PASS_FILE}`);
  const KEY_PASS = readFileSync(KEY_PASS_FILE, 'utf8').trim();
  const signed = join(OUT, 'signed.apk');
  run(join(BT, isWin ? 'apksigner.bat' : 'apksigner'), ['sign', '--ks', KEYSTORE, '--ks-key-alias', 'omega', '--ks-pass', `pass:${KEY_PASS}`, '--key-pass', `pass:${KEY_PASS}`, '--out', signed, aligned]);

  step(7, 'check (apksigner verify, aapt2 badging)');
  run(join(BT, isWin ? 'apksigner.bat' : 'apksigner'), ['verify', signed]);
  const badging = run(exe('aapt2'), ['dump', 'badging', signed]);
  const bytes = readFileSync(signed);
  const size = bytes.length;
  const info = { versionCode, versionName, size, sha256: createHash('sha256').update(bytes).digest('hex'), builtAt: new Date().toISOString() };

  // Put it where Omega Manager offers it to phones: the description first goes away, then the new APK and its new
  // description arrive, so a phone is never offered a file that doesn't match (phones check size and sha256).
  const apk = join(DIST, 'omega-manager.apk'), meta = join(DIST, 'omega-manager.json');
  writeFileSync(meta + '.tmp', JSON.stringify(info, null, 2));
  copyFileSync(signed, apk + '.tmp');
  rmSync(meta, { force: true });
  replace(apk + '.tmp', apk);
  replace(meta + '.tmp', meta);
  console.log(`\nBuilt ${relative(APP, apk)} — ${(size / 1024).toFixed(0)} KB, version ${versionName} (build ${versionCode})`);
  console.log('Phones with the app installed are told about it while Omega Manager runs.');
  return { apk, size, versionName, versionCode, badging, sha256: info.sha256 };
}

// The address phones use: OMEGA_PC_URL, else this PC's Tailscale name (https://<pc>.<tailnet>.ts.net:8444).
function pcAddress() {
  if (process.env.OMEGA_PC_URL) return process.env.OMEGA_PC_URL.trim();
  for (const ts of [isWin ? 'C:\\Program Files\\Tailscale\\tailscale.exe' : '', 'tailscale'].filter(Boolean)) {
    try {
      const st = JSON.parse(execFileSync(ts, ['status', '--json'], { encoding: 'utf8', windowsHide: true, stdio: ['ignore', 'pipe', 'ignore'], timeout: 10000 }));
      const dns = st?.Self?.DNSName?.replace(/\.$/, '');
      if (dns) return `https://${dns}:${PHONE_PORT}`;
    } catch { }
  }
  return '';
}

// Windows refuses to replace a file while it is being read (a phone downloading the old APK): try for a while.
function replace(from, to) {
  for (let i = 0; ; i++) {
    try { renameSync(from, to); return; } catch (e) {
      if (i >= 50 || !['EPERM', 'EBUSY', 'EACCES'].includes(e.code)) throw e;
      execFileSync(process.execPath, ['-e', 'setTimeout(() => {}, 200)']);
    }
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try { build(); } catch (e) { console.error(e.message); process.exit(1); }
}
